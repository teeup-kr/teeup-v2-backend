def create_default_terms(db: Session):
    """기본 약관 데이터 생성"""
    created_count = 0
    updated_count = 0
    
    for terms_type, terms_data in DEFAULT_TERMS_CONTENT.items():
        # 해당 타입의 활성화된 약관이 이미 있는지 확인
        existing_terms = db.query(Terms).filter(
            Terms.type == terms_type.value,  # enum 값을 문자열로 변환
            Terms.is_active == True
        ).first()
        
        if existing_terms:
            print(f"[이미 존재] {terms_data['title']} (ID: {existing_terms.id})")
            updated_count += 1
        else:
            # SQL로 직접 삽입 (ENUM 타입 문제 회피)
            try:
                sql = text("""
                    INSERT INTO terms (type, title, content, is_active, is_required, published_at, created_by, created_at, updated_at)
                    VALUES (:type, :title, :content, :is_active, :is_required, :published_at, :created_by, NOW(), NOW())
                """)
                result = db.execute(sql, {
                    "type": terms_type.value,
                    "title": terms_data['title'],
                    "content": terms_data['content'],
                    "is_active": True,
                    "is_required": terms_data['is_required'],
                    "published_at": datetime.now(),
                    "created_by": None
                })
                db.commit()
                
                # 생성된 ID 조회
                created_terms = db.query(Terms).filter(
                    Terms.type == terms_type.value,
                    Terms.title == terms_data['title']
                ).order_by(Terms.id.desc()).first()
                
                print(f"[생성 완료] {terms_data['title']} (ID: {created_terms.id if created_terms else 'N/A'}, 타입: {terms_type.value})")
                created_count += 1
            except Exception as e:
                db.rollback()
                print(f"[오류] {terms_data['title']} 생성 실패: {e}")
                # ENUM 타입 문제일 경우, ALTER TABLE로 ENUM 추가 시도
                if "Data truncated" in str(e) or "1265" in str(e):
                    print(f"  → ENUM 타입 업데이트 필요: {terms_type.value}")
                    # ENUM 업데이트는 수동으로 해야 할 수 있음
                raise
    
    return created_count, updated_count


